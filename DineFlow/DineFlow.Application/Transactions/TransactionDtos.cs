using System.ComponentModel.DataAnnotations;
using DineFlow.Domain.Orders;
using DineFlow.Domain.Payments;

namespace DineFlow.Application.Transactions;

/// <summary>Where a payment stands, including what happened to it after it succeeded.</summary>
public enum TransactionState
{
    /// <summary>Started; the provider hasn't confirmed it (it may have been abandoned).</summary>
    Pending,
    Succeeded,
    PartiallyRefunded,
    Refunded,
    Failed,
    Cancelled
}

public enum TransactionFilter { All, Succeeded, Refunded, Pending, Failed }

/// <param name="Search">A reference (e.g. DF-1A2B), a payment link (e.g. PL-1A2B), a table label (e.g. 7) or an amount (e.g. 73.70).</param>
public record TransactionQuery(
    [Required] Guid VenueId,
    DateTimeOffset? From = null,
    DateTimeOffset? To = null,
    TransactionFilter Status = TransactionFilter.All,
    [StringLength(40)] string? Search = null,
    [Range(1, 10_000)] int Page = 1,
    [Range(1, 100)] int PageSize = 25);

public record TransactionRowDto(
    Guid Id,
    string Reference,
    DateTimeOffset CreatedAt,
    DateTimeOffset? SucceededAt,
    TransactionState State,
    PaymentMethod Method,
    string? CardBrand,
    string? CardLast4,
    PaymentMode Mode,
    /// <summary>Empty for a payment through a payment link.</summary>
    string LocationType,
    string LocationLabel,
    /// <summary>The payment link it was paid through, e.g. PL-1A2B3C4D; null for a payment at the table.</summary>
    string? PaymentLinkCode,
    IReadOnlyList<int> OrderNumbers,
    string Currency,
    long AmountMinor,
    long TipMinor,
    long RefundedMinor,
    bool RefundPending,
    /// <summary>Where the payment stands with the venue's POS; null when it isn't posted to one (blueprint POSTED / POSTING_PENDING).</summary>
    string? PosStatus);

/// <summary>Money for the successful payments that match the filters (not just the current page).</summary>
public record TransactionTotalsDto(int Count, long GrossMinor, long TipsMinor, long RefundsMinor, long NetMinor);

public record TransactionPageDto(IReadOnlyList<TransactionRowDto> Items, int Total, int Page, int PageSize, TransactionTotalsDto Totals);

public record TransactionOrderLineDto(string Name, int Quantity, long LineTotalMinor);

public record TransactionOrderDto(Guid Id, int Number, OrderStatus Status, DateTimeOffset CreatedAt, IReadOnlyList<TransactionOrderLineDto> Lines, long TotalMinor);

public record RefundDto(
    Guid Id, long AmountMinor, string Reason, RefundStatus Status, string? FailureReason,
    string? RequestedBy, DateTimeOffset CreatedAt, DateTimeOffset? CompletedAt);

/// <summary>One step in a payment's life, for the timeline (blueprint 4.4 "complete payment timeline").</summary>
/// <param name="Text">The step in English, for clients that don't know its <paramref name="Code"/>.</param>
/// <param name="Code">What happened, e.g. "payment_paid", so the portal can word it in the reader's language.</param>
/// <param name="Params">The values that wording needs: amounts in minor units (keys ending in "Minor"), references, names.</param>
public record TimelineEventDto(DateTimeOffset At, string Kind, string Text, string? Code = null, object? Params = null);

public record TransactionDetailDto(
    TransactionRowDto Summary,
    string? AreaName,
    /// <summary>The payment link it was paid through; null for a payment at the table.</summary>
    Guid? PaymentLinkId,
    string? PaymentLinkReference,
    long BillAmountMinor,
    long DiscountMinor,
    string? PromoCode,
    long TipMinor,
    long AmountMinor,
    /// <summary>What can still be refunded: paid, minus refunds that succeeded or are pending.</summary>
    long RefundableMinor,
    int? Shares,
    int? SplitPeople,
    int ItemCount,
    string? FailureReason,
    int? ReviewRating,
    Guid? ReviewId,
    IReadOnlyList<TransactionOrderDto> Orders,
    IReadOnlyList<RefundDto> Refunds,
    IReadOnlyList<TimelineEventDto> Timeline);

/// <param name="ClientRequestId">Generated by the merchant app per refund; a retry returns the same refund.</param>
public record RefundRequest(
    [Required] Guid ClientRequestId,
    [Range(1, 100_000_000)] long AmountMinor,
    [Required, StringLength(200, MinimumLength = 1)] string Reason);
