using System.ComponentModel.DataAnnotations;
using HelloZen.Domain.Orders;

namespace HelloZen.Application.Orders;

// ---- Cart (guest) ----

/// <param name="MenuId">
/// The menu the guest added the item from, whose price applies while it's being served. Without
/// one, or once that menu stops, the price comes from the first menu being served.
/// </param>
public record CartLineRequest(
    [Required] Guid ItemId,
    [Range(1, OrderLine.MaxQuantity)] int Quantity,
    IReadOnlyList<Guid>? OptionIds,
    [StringLength(200)] string? Note,
    Guid? MenuId = null);

public record CartRequest([Required, MinLength(1), MaxLength(Order.MaxLines)] IReadOnlyList<CartLineRequest> Lines);

/// <param name="ClientRequestId">Generated by the guest app per submission and reused on retry.</param>
/// <param name="ExpectedTotalMinor">The total the guest saw; if the server's total differs the order is not placed.</param>
public record PlaceOrderRequest(
    [Required] Guid ClientRequestId,
    [Required, MinLength(1), MaxLength(Order.MaxLines)] IReadOnlyList<CartLineRequest> Lines,
    [StringLength(200)] string? Note,
    long? ExpectedTotalMinor);

/// <summary>
/// The server's price for a cart (P1-ORD-01): authoritative line prices, charges and total,
/// plus anything that stops it being ordered right now.
/// </summary>
public record CartQuoteDto(
    string Currency,
    IReadOnlyList<QuoteLineDto> Lines,
    long SubtotalMinor,
    long ServiceChargeMinor,
    int ServiceChargeBasisPoints,
    long TaxMinor,
    int TaxBasisPoints,
    bool TaxIncluded,
    long TotalMinor,
    IReadOnlyList<CartIssueDto> Issues)
{
    public bool CanOrder => Issues.Count == 0;
}

/// <param name="Index">Position of the line in the request, so the app can match issues to lines.</param>
public record QuoteLineDto(
    int Index,
    Guid ItemId,
    string Name,
    string? NameAr,
    int Quantity,
    long UnitPriceMinor,
    long LineTotalMinor,
    IReadOnlyList<OrderModifierDto> Modifiers,
    string? Note);

public record OrderModifierDto(Guid OptionId, string GroupName, string? GroupNameAr, string Name, string? NameAr, long PriceDeltaMinor);

/// <param name="Code">item_not_found, item_unavailable, menu_closed, option_not_found, option_unavailable or invalid_choices.</param>
public record CartIssueDto(int Index, string Code, string Message);

// ---- Orders ----

/// <param name="Number">The table's bill's number, shared by all its rounds.</param>
/// <param name="Round">1 for the table's first order, 2 for what it ordered next, and so on.</param>
public record OrderDto(
    Guid Id,
    int Number,
    int Round,
    OrderStatus Status,
    Guid VenueId,
    Guid ServiceLocationId,
    string LocationType,
    string LocationLabel,
    string? AreaName,
    Guid GuestSessionId,
    string Currency,
    IReadOnlyList<OrderLineDto> Lines,
    string? Note,
    long SubtotalMinor,
    long ServiceChargeMinor,
    long TaxMinor,
    bool TaxIncluded,
    long TotalMinor,
    string? RejectReason,
    DateTimeOffset CreatedAt,
    DateTimeOffset UpdatedAt);

public record OrderLineDto(
    Guid ItemId,
    string Name,
    string? NameAr,
    int Quantity,
    long UnitPriceMinor,
    long LineTotalMinor,
    IReadOnlyList<OrderModifierDto> Modifiers,
    string? Note);

/// <param name="Reason">Required when rejecting; shown to the guest.</param>
public record ChangeOrderStatusRequest(
    [Required] OrderStatus Status,
    [StringLength(200)] string? Reason);

/// <summary>Which orders the merchant queue shows.</summary>
public enum OrderFilter
{
    /// <summary>The board: every order not served yet, oldest first, then those served today.</summary>
    Active,
    /// <summary>Not ready yet (submitted, or accepted or preparing under the older flow).</summary>
    New,
    Ready,
    /// <summary>Served, with the table's bill not yet paid in full; newest first.</summary>
    Served,
    Rejected,
    /// <summary>Served and paid for in full; newest first.</summary>
    Closed,
    /// <summary>Every order whatever its stage, newest first: for looking one up.</summary>
    All
}

/// <summary>A stretch of the calendar at the venue: the day, week (Saturday to Friday), month, quarter or year around a date.</summary>
public enum OrderPeriod { All, Day, Week, Month, Quarter, Year }

/// <param name="Period">Only orders placed in this period; <see cref="OrderPeriod.All"/> for any time.</param>
/// <param name="Date">A day in the period, at the venue; today when left out.</param>
/// <param name="LocationId">Only orders for this table (or room, counter and so on).</param>
/// <param name="Number">Only the order with this number, e.g. 1024.</param>
/// <param name="Page">Which page of <see cref="MerchantOrderService.PageSize"/> orders to show, from 1.</param>
public record OrderQuery(
    OrderFilter Filter = OrderFilter.Active,
    OrderPeriod Period = OrderPeriod.All,
    DateOnly? Date = null,
    Guid? LocationId = null,
    [Range(1, int.MaxValue)] int? Number = null,
    [Range(1, 1_000)] int Page = 1);

internal static class OrderMapping
{
    public static OrderDto ToDto(this Order o) => new(
        o.Id, o.Number, o.Round, o.Status, o.VenueId, o.ServiceLocationId, o.LocationType, o.LocationLabel, o.AreaName,
        o.GuestSessionId, o.Currency,
        o.Lines.OrderBy(l => l.Position).Select(l => new OrderLineDto(
            l.MenuItemId, l.Name, l.NameAr, l.Quantity, l.UnitPriceMinor, l.LineTotalMinor,
            l.Modifiers.Select(ToDto).ToList(), l.Note)).ToList(),
        o.Note, o.SubtotalMinor, o.ServiceChargeMinor, o.TaxMinor, o.TaxIncluded, o.TotalMinor,
        o.RejectReason, o.CreatedAt, o.UpdatedAt);

    public static OrderModifierDto ToDto(this OrderLineModifier m) =>
        new(m.OptionId, m.GroupName, m.GroupNameAr, m.Name, m.NameAr, m.PriceDeltaMinor);
}
