/** Arabic counted noun: 1 and 2 have their own forms, 3–10 take the plural, 11+ the singular. */
function arCount(n: number, one: string, two: string, few: string, many: string): string {
  if (n === 1) return one;
  if (n === 2) return two;
  return n % 100 >= 3 && n % 100 <= 10 ? `${n} ${few}` : `${n} ${many}`;
}

